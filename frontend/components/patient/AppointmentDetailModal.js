'use client';

import { AlertCircle, ListOrdered, QrCode, XCircle } from 'lucide-react';
import { Modal } from '@/components/common/Modal';
import { Button, ButtonLink } from '@/components/common/Button';
import { StatusBadge } from '@/components/common/Badge';
import { canTrack, queueHref } from '@/components/patient/AppointmentCard';
import { doctorDisplayName, formatDate, formatTime } from '@/lib/utils';

function Fact({ label, children }) {
  return (
    <div>
      <dt className="text-sm text-slate-600">{label}</dt>
      <dd className="text-lg font-semibold text-ink-900">{children}</dd>
    </div>
  );
}

export function AppointmentDetailModal({ appointment, onClose, onCancel }) {
  const a = appointment;
  return (
    <Modal open={!!a} onClose={onClose} title="Appointment details" size="md">
      {a ? (
        <div className="flex flex-col gap-5">
          <div className="flex items-start justify-between gap-3">
            <div>
              <p className="text-xl font-semibold text-ink-900">{doctorDisplayName(a.doctorId)}</p>
              {a.doctorId?.specialization ? <p className="text-slate-600">{a.doctorId.specialization}</p> : null}
            </div>
            <StatusBadge status={a.status} />
          </div>

          <dl className="grid grid-cols-2 gap-4 rounded-xl bg-ivory-2 p-4">
            <Fact label="Date">{formatDate(a.date)}</Fact>
            <Fact label="Time">{formatTime(a.slotTime)}</Fact>
            <Fact label="Token number">
              <span className="text-2xl text-brand-800">#{a.tokenNumber}</span>
            </Fact>
            {a.isEmergency ? (
              <Fact label="Type">
                <span className="inline-flex items-center gap-1.5 text-red-700">
                  <AlertCircle className="h-5 w-5" aria-hidden="true" /> Emergency
                </span>
              </Fact>
            ) : null}
          </dl>

          {a.symptoms ? (
            <div>
              <h3 className="text-lg font-semibold">Symptoms you described</h3>
              <p className="mt-1 whitespace-pre-wrap text-slate-700">{a.symptoms}</p>
            </div>
          ) : null}

          {a.notes ? (
            <div className="rounded-xl bg-brand-50 p-4">
              <h3 className="text-lg font-semibold text-brand-800">Doctor’s notes</h3>
              <p className="mt-1 whitespace-pre-wrap text-slate-800">{a.notes}</p>
            </div>
          ) : null}

          {a.status === 'booked' && a.qrCode ? (
            <div className="flex flex-col items-center gap-2 rounded-xl border border-slate-200 p-4 text-center">
              <p className="inline-flex items-center gap-2 text-base font-semibold text-ink-900">
                <QrCode className="h-5 w-5" aria-hidden="true" /> Show this code at reception
              </p>
              {/* Data-URL QR code generated by the backend - next/image adds nothing here. */}
              {/* eslint-disable-next-line @next/next/no-img-element */}
              <img src={a.qrCode} alt={`QR code for token ${a.tokenNumber}`} className="h-44 w-44" />
            </div>
          ) : null}

          {canTrack(a) ? (
            <div className="flex flex-col gap-3 sm:flex-row">
              <ButtonLink href={queueHref(a)} icon={ListOrdered} full>
                Track my queue
              </ButtonLink>
              {a.status === 'booked' ? (
                <Button variant="danger" icon={XCircle} full onClick={() => onCancel?.(a)}>
                  Cancel appointment
                </Button>
              ) : null}
            </div>
          ) : null}
        </div>
      ) : null}
    </Modal>
  );
}
